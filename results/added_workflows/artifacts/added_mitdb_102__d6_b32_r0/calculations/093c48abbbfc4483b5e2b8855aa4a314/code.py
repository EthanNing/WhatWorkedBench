
import numpy as np
masks=[format(i,'06b') for i in range(64)]
X=np.array([[int(c) for c in m] for m in masks],float); Z1=2*X-1
cols=[np.ones(64)]+[Z1[:,j] for j in range(6)]+[Z1[:,a]*Z1[:,b] for a in range(6) for b in range(a+1,6)]
Z=np.column_stack(cols)
anchors=[masks.index('000000'),masks.index('111111')]
# edge functional vectors: for edge (v, v^e_j): z(v)-z(v^e_j)
D=[]
for v in range(64):
    for j in range(6):
        w=v^(1<<j)
        if v<w:
            D.append(Z[v]-Z[w])
D=np.array(D)  # 192 x 22
cands={
 'D26':['000001','000011','000100','000110','001000','001010','001101','001111','010000','010010','010101','010111','011001','011011','011100','011110','100000','100010','100101','100111','101001','101010','101011','101100','101110','110001','110011','110100','110110','111000','111010','111101'],
 'D33':['000001','000010','000011','000100','000110','001000','001101','001111','010000','010010','010101','010111','011001','011011','011100','011101','011110','100000','100101','100111','101001','101010','101011','101100','101110','110001','110011','110100','110101','110110','111000','111010'],
 'D42':['000001','000010','000011','000100','000110','001000','001010','001101','010000','010111','011001','011011','011100','011101','011110','100000','100101','100111','101000','101001','101010','101011','101100','101101','101110','110000','110001','110011','110100','110110','111000','111010'],
 'D55':['000001','000010','000011','000100','000110','001000','001111','010000','010001','010010','010011','010111','011001','011011','011101','011110','011111','100000','100001','100011','100101','100111','101000','101001','101010','101100','110000','110001','110010','110011','110100','111000'],
}
edges=[(i,i^(1<<j)) for i in range(64) for j in range(6) if i<(i^(1<<j))]
for name,ch in cands.items():
    S=anchors+[masks.index(m) for m in ch]
    M=Z[S]; G=M.T@M
    Ginv=np.linalg.inv(G+1e-9*np.eye(22))
    var=np.einsum('ij,jk,ik->i',D,Ginv,D)
    Ss=set(S); cov=sum(1 for i,k in edges if i in Ss and k in Ss)
    print(name,"edges",cov,"mean pred var (deg2)",round(var.mean(),4),"max",round(var.max(),4))
